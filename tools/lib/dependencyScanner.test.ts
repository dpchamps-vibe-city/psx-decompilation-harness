import { test } from "../testing/runtimeTestContext.js";
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { projectFixture } from "../testing/projectFixture.js";
import { compilationIdentity, stableHash } from "./cacheIdentity.js";
import { compileObject } from "../build/pipeline.js";
import { cachedPreprocess } from "../agent/preprocessedCache.js";
import { sourceDependencyFiles } from "../agent/decompToolchain.js";
import { fixtureContext } from "../testing/runtimeTestContext.js";
import { dependencyScannerIdentity } from "./dependencyScanner.js";

test("production cpp does not receive dependency/driver flags; separate scanner serves build and cache", t => {
  const f = projectFixture(t), original = f.toolchain.tools.cpp;
  assert.equal(typeof original, "string");
  const wrapper = join(f.root, "period-cpp.mjs"), log = join(f.root, "cpp-argv.jsonl");
  writeFileSync(wrapper, `#!${process.execPath}\nimport {appendFileSync} from 'node:fs';import {spawnSync} from 'node:child_process';const a=process.argv.slice(2);appendFileSync(${JSON.stringify(log)},JSON.stringify(a)+'\\n');if(a.some(x=>/^-M|^-print-prog-name/.test(x)))process.exit(73);const r=spawnSync(${JSON.stringify(original)},a,{stdio:'inherit'});process.exit(r.status??1);\n`, { mode: 0o755 });
  f.toolchain.tools.cpp = wrapper; f.toolchain.tools.dependencyScanner = original;
  delete f.toolchain.tools.cppFrontend;
  f.put("toolchain.json", JSON.stringify(f.toolchain));
  f.put("include/value.h", "#define VALUE 7\n");
  f.put("src/provenance.c", '#include "value.h"\nint provenance(void) { return VALUE; }\n');
  const container = f.containers().find(c => c.id === "exe")!;
  const object = compileObject(container, "src/provenance.c", f.root);
  assert.ok(readFileSync(object).length);
  assert.match(readFileSync(`${object}.d`, "utf8"), /value\.h/);
  assert.equal(JSON.parse(readFileSync(`${object}.d.scanner.json`, "utf8")).sha256, dependencyScannerIdentity(f.root).sha256);
  const before = stableHash(compilationIdentity(f.root));
  const cold = cachedPreprocess(join(f.root, "src/provenance.c"), f.root);
  assert.match(cold.text, /return 7/);
  assert.equal(cachedPreprocess(join(f.root, "src/provenance.c"), f.root).cache, "hit");
  const deps = fixtureContext(f.root, () => sourceDependencyFiles("src/provenance.c", { kind: "exe", id: "exe" }, f.root));
  assert.ok(deps.includes(join(f.root, "include/value.h")));
  const scanner = join(f.root, "scanner.sh");
  writeFileSync(scanner, `#!/bin/sh\nexec ${JSON.stringify(original)} "$@"\n`, { mode: 0o755 });
  f.toolchain.tools.dependencyScanner = scanner; f.put("toolchain.json", JSON.stringify(f.toolchain));
  assert.equal(stableHash(compilationIdentity(f.root)), before, "scanner does not produce compilation bytes");
  f.put("include/value.h", "#define VALUE 9\n");
  assert.match(cachedPreprocess(join(f.root, "src/provenance.c"), f.root).text, /return 9/);
  const calls = readFileSync(log, "utf8").trim().split("\n").map(line => JSON.parse(line));
  assert.ok(calls.length >= 3);
  assert.ok(calls.every(a => !a.some((x: string) => /^-M|^-print-prog-name/.test(x))));
});

test("original inventory migration dry-runs, then transactionally rewrites sources and runtime state", t => {
  const f = projectFixture(t);
  f.toolchain.flags.as = ["-EL", "-G0", "-mips1"];
  f.put("toolchain.json", JSON.stringify(f.toolchain));
  f.put("view.s", ".text\n.set noreorder\n.globl entry\nentry:\njr $31\nnop\n.type private_entry,@function\nprivate_entry:\njr $31\nnop\n.size private_entry,.-private_entry\n");
  execFileSync(f.toolchain.tools.as as string, [...f.toolchain.flags.as, join(f.root, "view.s"), "-o", join(f.root, "view.o")]);
  const text = readRelocatableObject(readFileSync(join(f.root, "view.o"))).sections.get(".text")!.data;
  const u16 = (n: number) => { const b = Buffer.alloc(2); b.writeUInt16LE(n); return b; };
  const u32 = (n: number) => { const b = Buffer.alloc(4); b.writeUInt32LE(n); return b; };
  const str = (s: string) => Buffer.concat([Buffer.from([s.length]), Buffer.from(s)]);
  const lnk = Buffer.concat([Buffer.from("4c4e4b02", "hex"), Buffer.from([16]), u16(1), u16(0), Buffer.from([16]), str(".text"), Buffer.from([6]), u16(1), Buffer.from([2]), u16(text.length), text, Buffer.from([12]), u16(1), u16(1), u32(0), str("entry"), Buffer.from([0])]);
  f.put("ORIGINAL.OBJ", lnk);
  const base = { schemaVersion: 1, target: { kind: "relocatable-library", format: "elf-ar", standaloneObjects: ["view.o"] }, output: { sourceDir: "src/libraries", sourceLayout: "tu-directory", inputRoot: "." } };
  f.put("project.json", JSON.stringify(base));
  fixtureContext(f.root, () => {
    const id = libraryMembers(f.root)[0]!.id;
    f.put("project.json", JSON.stringify({ ...base, verification: { mode: "original-object", originals: { format: "psyq-lnk", archives: [], objects: ["ORIGINAL.OBJ"], map: { [id]: { object: "ORIGINAL.OBJ" } } } } }));
    f.put("src/libraries/view/tu.json", JSON.stringify({ schemaVersion: 1, member: id, parts: [{ path: "entry.c", symbol: "entry" }, { path: "private_entry.c", symbol: "private_entry" }] }));
    f.put("src/libraries/view/entry.c", "int entry(void) { return 0; }\n");
    f.put("src/libraries/view/private_entry.c", "static void private_entry(void) {}\n");
    const member = libraryMembers(f.root)[0]!;
    assert.ok(member.object.symbols.some(s => s.name === "private_entry" && s.type === 2));
    assert.ok(!member.originalObject!.object.symbols.some(s => s.name === "private_entry"), "diagnostic bounds never alter native identity");
    assert.equal(libraryFunctionTarget(member, member.functions[0]!).verification.mode, "original-object");
    const provenance = computeProvenance(`${id}::entry`, {}), workspace = libraryWorkspaceIdentity([member]), beforeBatch = libraryBuildIdentities();
    assert.ok(provenance.files["ORIGINAL.OBJ"]);
    assert.ok(provenance.files["view.o"]);
    assert.ok(computeProvenance("entry", {}).files["ORIGINAL.OBJ"]);
    assert.throws(() => computeProvenance("missing::entry", {}), /Unknown native provenance member/);
    const changed = Buffer.from(lnk); changed[9] = 8; // Native alignment, invisible to ELF-view correspondence.
    f.put("ORIGINAL.OBJ", changed);
    assert.throws(() => libraryWorkspaceIdentity([member]), /Original input changed/);
    assert.throws(() => libraryBuildIdentity(member), /Original input changed/);
    assert.throws(() => beforeBatch.identity(member), /Original input changed/);
    assert.throws(() => withLibraryMetadata(() => computeProvenance(`${id}::entry`, {}), [member]), /Original input changed/);
    assert.notEqual(computeProvenance(`${id}::entry`, {}).fingerprint, provenance.fingerprint);
    assert.notEqual(libraryWorkspaceIdentity(libraryMembers(f.root)), workspace);
    f.put("ORIGINAL.OBJ", lnk);
    const target = assembleTarget(`${id}::private_entry`, "build/native-target");
    assert.ok(readFileSync(target).equals(lnk), "diagnostics retain the original LNK, not the ELF view");
    assert.equal(disassembleObject(target)[0]!.address, 8);
    assert.equal(disassembleFunctionObject(target, `${id}::private_entry`)[0]!.mnemonic, "jr");
    f.put("notes/member.md", `${id}::entry\n`);
    f.put("configs/project-profile.md", `# Generated profile\n${id}\n`);
    f.put(`run_output/autoloop/attempts/${id}__entry/source.c`, `/* ${id} */\n`);
    const report = migrateMemberIds(false, f.root);
    assert.equal(report.mapping[id], "original");
    assert.equal(report.written, false);
    assert.ok(report.changes.some(c => c.path === "configs/project-profile.md" && c.regenerate));
    assert.match(readFileSync(join(f.root, "notes/member.md"), "utf8"), new RegExp(id));
    // No accepted record: a known mismatch may migrate, but only if a fresh
    // production build has the same result after the rename.
    f.put("notes/unmapped.md", "lib_0123456789abcdef_9::entry\n");
    assert.throws(() => migrateMemberIds(false, f.root), /Unmapped old member ID/);
    rmSync(join(f.root, "notes/unmapped.md"));
    f.put("run_output/autoloop/attempts/original__entry/collision.txt", "existing\n");
    assert.throws(() => migrateMemberIds(false, f.root), /directory collision/);
    rmSync(join(f.root, "run_output/autoloop/attempts/original__entry"), { recursive: true });
    f.put("run_output/autoloop/active.json", "{}\n");
    assert.throws(() => migrateMemberIds(true, f.root), /Stop the autoloop/);
    rmSync(join(f.root, "run_output/autoloop/active.json"));
    const originalProject = readFileSync(join(f.root, "project.json"));
    f.put("configs/project-info.json", "{");
    assert.throws(() => migrateMemberIds(true, f.root), /JSON/);
    assert.ok(readFileSync(join(f.root, "project.json")).equals(originalProject), "failed profile generation rolls back the transaction");
    assert.ok(!existsSync(join(f.root, "run_output/autoloop/attempts/original__entry")), "rollback removes newly created ID directories");
    assert.match(readFileSync(join(f.root, "configs/project-profile.md"), "utf8"), new RegExp(id));
    f.put("configs/project-info.json", "{}");
    f.put(`build/preparation/${id}/packet.json`, "{}");
    f.put("build/callGraph.json", JSON.stringify({ member: id }));
    f.put(`build/libraries/receipts/${id}.json`, "{}");
    const applied = migrateMemberIds(true, f.root);
    assert.equal(applied.written, true);
    assert.equal(applied.results![0]!.verdict, "mismatch");
    assert.equal(libraryMembers(f.root)[0]!.id, "original");
    assert.equal(readFileSync(join(f.root, "notes/member.md"), "utf8"), "original::entry\n");
    assert.ok(existsSync(join(f.root, "run_output/autoloop/attempts/original__entry/source.c")));
    assert.ok(!existsSync(join(f.root, `run_output/autoloop/attempts/${id}__entry`)), "old-ID directories are removed too");
    assert.ok(!existsSync(join(f.root, "build/libraries")));
    assert.ok(!existsSync(join(f.root, "build/preparation")));
    assert.ok(!existsSync(join(f.root, "build/callGraph.json")));
    assert.doesNotMatch(readFileSync(join(f.root, "configs/project-profile.md"), "utf8"), /lib_[0-9a-f]{16}_\d+/);
    assert.equal(originalMemberId("TEST.LIB", 33), "test_33");
    splitLibrary(f.root);
    assert.ok(existsSync(join(f.root, "build/libraries/nonmatchings/original/entry.s")), "native-ID splits still derive source paths from the ELF views");
    const outside = projectFixture(t);
    outside.put("escaped.o", readFileSync(join(f.root, "view.o")));
    rmSync(join(f.root, "view.o"));
    symlinkSync(join(outside.root, "escaped.o"), join(f.root, "view.o"));
    assert.throws(() => libraryMembers(f.root), /Input escapes project/);
  });
});

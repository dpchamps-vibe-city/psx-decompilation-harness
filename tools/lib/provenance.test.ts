    const accepted = JSON.parse(readFileSync(join(f.root, `build/libraries/verified/${member.id}.json`), "utf8"));
    assert.equal(accepted.originalHash, accepted.candidateHash);
    assert.equal(accepted.toolchain.as.sha256, f.toolchain.toolPins!.as!.sha256);
    assert.equal(receipt.lnkLayout, "standard");
    assert.equal(receipt.stages[1].name, "psyq-lnk");

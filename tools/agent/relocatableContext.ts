/** Context publication for the relocatable adapter. Per-owner files prevent
 * duplicate/local symbol names from merging unrelated TU scopes. Reference
 * headers are read through the target cpp, never overwritten. */
import { existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { HARNESS_ROOT, configuredFlags, configuredTool } from "../lib/toolchain.js";
import { libraryMembers, requireLibraryFunction } from "../lib/libraryTargets.js";
import { resolveFunctionTarget } from "../lib/targetAdapter.js";
import { measureLibraryFunction, libraryBuildIdentity } from "./libraryTarget.js";
import { prepareM2c } from "../build/prepareM2c.js";
import { runTool } from "./decompToolchain.js";
import { emptyDeclarationIndex, indexDeclarations, projectDeclarations } from "./declarationContext.js";
import { extractSignaturesFromSource } from "./sdkTypes.js";
import { analyzeCSource } from "./cSourceGuard.js";
import { writeIfChanged } from "../lib/contentCache.js";
import { loadConfig } from "../../.pi/extensions/shared/config.js";
import { sourceConstructFindings } from "../../.pi/extensions/shared/source-policy.js";
import type { ExportResult } from "./contextExport.js";

export function exportRelocatableContext(name: string, root = HARNESS_ROOT, dryRun = false): ExportResult {
  root = resolve(root);
  if (root !== HARNESS_ROOT) throw new Error("Publish context from the target's cloned harness root");
  const target = resolveFunctionTarget(name, root);
  const skipped = (reason: string): ExportResult => ({ status: "skipped", skipped: true, signatureMatches: false, signatures: [], localPrototypes: [], reason });
  if (!existsSync(join(root, target.source))) return skipped("file not found");
  const before = requireLibraryFunction(target.key, root).member;
  const identity = libraryBuildIdentity(before, root);
  const measured = measureLibraryFunction(target.key);
  const { member, comparison, artifacts } = measured;
  if (before.sha256 !== member.sha256 || identity !== libraryBuildIdentity(member, root)) throw new Error("Publication inputs changed during compile; rerun context export");
  const source = readFileSync(artifacts.source, "utf8"), guard = analyzeCSource(source);
  const findings = sourceConstructFindings(source, loadConfig(root), { name: target.owner.id, container: target.owner.id });
  const preprocessed = readFileSync(artifacts.preprocessed, "utf8");
  const includesGeneratedContext = /#\s*\d+\s+"[^"]*build\/libraries\/context\//.test(preprocessed);
  if (!guard.parses || guard.includeAsm.length || includesGeneratedContext || findings.length || comparison.verdict !== "match")
    return skipped(`clean C and a fresh ${target.verification.scope} MATCH required (${comparison.verdict}; ${findings.map(f => f.message).join("; ")})`);
  const pairs = extractSignaturesFromSource(preprocessed);
  if (member.functions.some(fn => !pairs.some(p => p.name === fn.name))) return skipped("inventoried function definition missing");
  const index = emptyDeclarationIndex();
  indexDeclarations(index, preprocessed, artifacts.preprocessed, member.id, "source-local");
  // Take types from the compiler's actual scope, not prototypes that conflict
  // merely because parameter names differ between a header and its definition.
  index.declarations = index.declarations.filter(d => d.kind === "type");
  indexDeclarations(index, pairs.map(p => p.signature).join("\n"), target.source, member.id, "source-local");
  const projection = projectDeclarations(index, pairs.map(p => p.name), member.id);
  if (projection.unknown.length) throw new Error(`Cannot publish context: unresolved types ${projection.unknown.join(", ")}`);
  const types = emptyDeclarationIndex(); types.declarations = projection.selected.filter(d => d.kind === "type");
  const banner = "/* Auto-generated by tools/agent/contextExport.ts — m2c context only; do not include in compiler sources. */\n";
  const contents = new Map([
    [join(root, target.context.types), banner + projectDeclarations(types, types.declarations.map(d => d.name), member.id).text],
    [join(root, target.context.functions), banner + pairs.map(p => p.signature).sort().join("\n") + "\n"],
  ]);
  if (dryRun) for (const text of contents.values()) process.stdout.write(text);
  else {
    const previous = new Map([...contents.keys()].map(path => [path, existsSync(path) ? readFileSync(path, "utf8") : null]));
    try {
      for (const [path, text] of contents) { mkdirSync(dirname(path), { recursive: true }); writeIfChanged(path, text); }
      const m2c = prepareM2c(root);
      const output = runTool(configuredTool("python", root), [m2c.script, ...configuredFlags("m2c", target.flags, root), "--no-cache",
        "-f", target.symbol, "--context", target.context.types, "--context", target.context.functions, target.assembly.translationUnit], root);
      if (output.includes("Syntax error when parsing C context")) throw new Error(output);
      if (identity !== libraryBuildIdentity(member, root)) throw new Error("Publication inputs changed; rerun context export");
    } catch (error) {
      for (const [path, text] of previous) { if (text === null) rmSync(path, { force: true }); else writeIfChanged(path, text); }
      throw error;
    }
  }
  return { status: "published", skipped: false, signatureMatches: true, signatures: pairs.map(p => p.signature), localPrototypes: [] };
}

export function exportAllRelocatableContexts(root = HARNESS_ROOT, dryRun = false): { exported: string[]; skipped: string[] } {
  const exported: string[] = [], skipped: string[] = [];
  for (const member of libraryMembers(root)) {
    const fn = member.functions[0];
    if (!fn || !existsSync(join(root, member.source)) || analyzeCSource(readFileSync(join(root, member.source), "utf8")).includeAsm.length) { skipped.push(member.id); continue; }
    const result = exportRelocatableContext(`${member.id}::${fn.name}`, root, dryRun);
    (result.skipped ? skipped : exported).push(member.id);
  }
  return { exported, skipped };
}
